#!/usr/bin/env python
"""
run_inject_v3.py -- inject Bonnor-Ebert sphere models into Herschel maps.

DO NOT EDIT THIS FILE.  All settings live in a config file.

WHAT CHANGED IN VERSION 3
-------------------------
Version 3 rebuilds the way a model is matched to a place in the map.  Four
independent defects of version 2 are corrected; each is documented in full at
the point where it is fixed, and each is summarised here.

1. The embedding window is now symmetric.  The rungs of the model grid in
   embedding column SD_emb are spaced by a factor of 2, but version 2 allowed
   a model to be placed only where the local column lay in
   [SD_emb, sqrt(2)*SD_emb), a window half a rung wide.  The upper half of
   every octave therefore belonged to no model.  Of the 1030 real Aquila
   sources, 520 sit at columns inside those gaps, and so does the median
   column of the population, 5.04e21 cm^-2.  Models drawn for such columns
   fell through to a nearest-rung fallback that always selected the rung
   above, and were then placed at columns higher than the ones drawn.  This
   was the main cause of the injected sample being displaced toward high
   column density.  See inject.valid_placement_mask.

2. Models are selected and separated by their observed size, not by R_BE.
   The truncation radius R_BE is not an observable: grid nodes with R_BE
   between 136 and 428 arcsec present a surface-density half-maximum width
   FWHMSDbs of only 25 to 50 arcsec, well inside the range of the real
   sources.  Cutting on R_BE discarded every node above 1.8 solar masses and
   gave the surviving models exclusion zones far larger than their apparent
   extent, which is why a few large faint models consumed the usable area.
   FWHM_MIN_AS and FWHM_MAX_AS replace R_BE_MIN_AS and R_BE_MAX_AS.

3. The mass match is made against the model's own reported SED mass,
   M_SED4bs, rather than against its true mass M_BE.  The target masses are
   reported SED masses of real sources, and over the eligible nodes the ratio
   M_BE / M_SED4bs has median 1.105, so matching against M_BE built in a
   systematic offset of 0.043 in base-10 logarithm.

4. Real-source footprints are avoided by the core center only, with a fixed
   margin, instead of by the whole R_BE disk.  The footprints cover 6.5% of
   the sub-field; eroding by an R_BE of 70 arcsec turned that into most of
   the field, which is why avoidance had been switched off altogether.

The target distribution itself is now built by build_joint_target_v3.py and
carries a fourth column, the observed size of each real source.

USAGE
-----
  python -B run_inject.py                        # uses inject_config.py
  python -B run_inject.py inject_config_set3     # uses inject_config_set3.py
  python -B run_inject.py inject_config_i1j2k4   # single-model config

CONFIG FILE FORMATS
-------------------
Multi-model (preferred for Tier-2):
  SET_TAG = 'set3'
  MODELS  = [ dict(tag=..., sd_emb=..., r_be_arcsec=..., stamp_files={...}), ... ]
  Separation computed automatically: sqrt((2*R_BE_max)^2 + 36.3^2).

Single-model (backward compatible):
  MODEL_TAG, SD_EMB, R_BE_ARCSEC, STAMP_FILES, MIN_SEP_ARCSEC

Both formats share field paths via inject_config_field.py (on PYTHONPATH
or in the same directory as this script / its Python/ subdirectory).

DEPENDENCIES
------------
  pip install numpy astropy scipy
"""

