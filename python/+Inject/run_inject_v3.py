# forbidden to the centers of injected cores.  In version 2 this was switched
# off because the exclusion appeared to cost 87% of the sub-field.  That figure
# was an artifact: the footprints themselves cover 6.5% of the field, in 179
# filled regions of median area 242 pixels, and the 87% arose from eroding the
# permitted region by the whole R_BE disk, which for R_BE = 70 arcsec dilates
# each footprint by 23 pixels.  Version 3 applies the exclusion to the core
# center with the fixed margin FOOTPRINT_MARGIN_AS, so the true cost is a few
# per cent, and the default is therefore on.  What has to be prevented is
# centering an injected core on a real one, which makes the extraction a blend
# of the two; overlap of the outer envelope with a real footprint is harmless
# and in any case unavoidable in a real cloud.
AVOID_REAL_FOOTPRINTS = bool(getattr(_cfg, 'AVOID_REAL_FOOTPRINTS', True))
# OVERLAP_FREE_R_BE_AS separates compact models from large ones for the purpose
# of the non-overlap criterion.  Requiring every pair to be separated is too
# strong: a large, faint, flat-topped model is barely detectable against the
# cloud and does not disturb the measurement of a small core lying on top of it,
# yet its exclusion zone denies that core the dense filament where it belongs.
# The criterion is therefore applied only within a class: two compact models may
# not overlap, and two large models may not overlap either, since intersecting
# flat tops would double the intensity over an extended area and create an
# artifact.  A compact model may be placed on a large one.  Set to None to
# restore the criterion for every pair.
#
# In version 3 the class boundary and the exclusion radius are both expressed
# in the observed size FWHMSDbs rather than in R_BE, for the reason given in
# point 2 of the module docstring.  The default, 50 arcsec, is a little above
# the median AFWHM of the real Aquila sources, 37.8 arcsec.
OVERLAP_FREE_FWHM_AS = getattr(_cfg, 'OVERLAP_FREE_FWHM_AS', 50.0)
# MAX_FOOTPRINT_OVERLAP, when set, replaces the size-class rule above by a
# criterion applied to EVERY pair: the footprints of two injected cores may
# interpenetrate by at most this fraction of the sum of their footprint radii,
# so that
#     centre separation  >=  (1 - MAX_FOOTPRINT_OVERLAP) * (R_foot_i + R_foot_j)
# with R_foot = 0.5 * FOOTPRINT_FACTOR * FWHMSDbs.
#
# The size-class exemption it replaces let a compact model be placed on an
# extended one without any separation requirement, on the argument that a large
# faint model is barely detectable against the cloud and would not disturb a
# small core lying on it.  Measured on the first population-matched injection,
# that argument fails: 36% of injected cores ended up with a companion closer
# than the sum of their two half-maximum radii, every close pair was a
# cross-class pair, the closest was at 0.11 of that sum, and the error in the
# recovered mass correlates with crowding at +0.42 (probability 0.011) in the
# flattened run, crowded cores losing flux to their companions.
MAX_FOOTPRINT_OVERLAP = getattr(_cfg, 'MAX_FOOTPRINT_OVERLAP', 0.10)
