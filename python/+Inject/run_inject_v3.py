# from the footprint of a REAL source.
#
#   'fixed'   FOOTPRINT_MARGIN_AS, the same for every model.  This keeps an
#             injected core from being centred on a real one but does nothing
#             about the overlap of their footprints: measured on the first
#             population-matched injection, 14% of injected cores overlapped a
#             real footprint and 9% did so by more than a tenth of the sum of
#             the two radii.  A real source inside an injected footprint
#             contributes flux that the extraction cannot attribute correctly,
#             which is the same contamination as two overlapping models.
#
#   'scaled'  (1 - MAX_FOOTPRINT_OVERLAP) * R_foot of the model being placed,
#             with R_foot = 0.5 * FOOTPRINT_FACTOR * FWHMSDbs.  Because the
#             footprint map already covers each real source out to its own
#             footprint radius, eroding by this amount leaves the injected
#             centre at least that distance beyond the real footprint edge, so
#             the two footprints overlap by no more than the permitted
#             fraction.  This is the same criterion applied between injected
#             cores, extended to the real ones.
FOOTPRINT_MARGIN_MODE = getattr(_cfg, 'FOOTPRINT_MARGIN_MODE', 'scaled')

# STAMP_SUFFIX selects which background-subtracted model stamp is injected, and
# with it which set of grid-catalogue columns describes the injected core.  The
# grid provides both, and the catalogue header defines them:
#
#   'bsl'  true crater background.  The background actually removed is the
#          floor of the depression the model digs in the cloud it displaces, so
#          the stamp is the model's own excess and is non-negative everywhere.
#   'bs'   interpolated background.  A flat background at the cloud level is
#          removed instead.  Where a model's outer envelope is rarer than the
#          cloud it replaces, the model dips BELOW that level, and the stamp is
#          negative in an annulus inside R_BE.
#
# Versions up to this one injected 'bs', on the reasoning that getsf later
# subtracts an interpolated background by the same construction, so the choice
# would cancel.  It does not.  Injecting 'bs' writes the negative annulus into
# the map, which removes flux around the core and from any neighbour reaching
# into it, and makes the source-only image negative there.  The cancellation
# argument also fails because getsf interpolates over the real map, whose
# background is not the model's embedding cloud.  15% of the grid's nodes are
# affected, rising to 56% at the highest embedding column; flag_hole_models.py
# lists them.  The default is therefore 'bsl'.
#
# The choice propagates to the selection: the contrast a node will show and its
# reported SED mass must be read from the matching set of columns, ICSD<suffix>
# and M_SED4<suffix>, or the model chosen will not be the model injected.
# CONTROL_ISOLATED produces the isolated control of a blending pair.  The
# placement is carried out in full and unchanged, consuming the random number
# generator identically, and only then are the cores that overlap a kept one
# removed, leaving a maximal non-overlapping subset in placement order.
#
# Every core that survives is therefore the same model, at the same position,
# on the same background, in the same field, as in the companion run made with
# the same seed and CONTROL_ISOLATED off.  The comparison can then be made core
# by core.  This matters: the flattened and unflattened pair, compared sample
# against sample, appeared to show a 39% bias from the cloud fluctuations that
# vanished once the same cores were compared, the apparent effect having been
# sampling.  A control produced by re-running with a stricter separation rule
# would place different models in different places and would suffer the same
# confusion; this one cannot.
#
# The truth table of the control is a strict subset of the companion's, so the
# pairing can be verified by comparing model tags and positions.
CONTROL_ISOLATED = bool(getattr(_cfg, 'CONTROL_ISOLATED', False))

