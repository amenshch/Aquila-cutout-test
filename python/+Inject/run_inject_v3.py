_R_FLUX = None


def _flux_radii(path=None, frac=None):
    """{node tag: radius enclosing `frac` of the model's flux}, in arcsec.

    Computed from the azimuthally averaged surface-density profiles, weighting
    each radial bin by 2 pi r I(r) dr on the uniform radial grid the profiles
    use.  Returns an empty dict, with a warning, if the file is absent, so that
    the caller can fall back on the geometric radii.
    """
    global _R_FLUX
    if _R_FLUX is not None:
        return _R_FLUX
    path = path or BES_PROFILES
    frac = FLUX_FRACTION if frac is None else frac
    prof = {}
    try:
        if not path or not os.path.exists(path):
            raise IOError('no such file: %r' % (path,))
        for line in open(path):
            if not line.strip() or line.lstrip()[0] == '#':
                continue
            f = line.split()
            if f[3] != 'SD':
                continue
            tag = 'i%02dj%02dk%02d' % (int(f[0]), int(f[1]), int(f[2]))
            prof.setdefault(tag, []).append((float(f[5]), float(f[6])))
    except (IOError, OSError, TypeError, ValueError, IndexError) as _e:
        print('  NOTE: the profiles catalogue could not be read (%s); '
              'exclusion radii fall back to the larger of R_BE and the '
              'observed footprint, which is conservative for concentrated '
              'models and may drop some of them from the injection' % _e)
        _R_FLUX = {}
        return _R_FLUX
    out = {}
    for tag, pts in prof.items():
        a = np.asarray(sorted(pts), float)
        r, I = a[:, 0], a[:, 1]
        w = np.cumsum(np.maximum(I, 0.0) * r)
        if w[-1] <= 0:
            continue
        out[tag] = float(np.interp(frac, w / w[-1], r))
    print('  exclusion radii: %d nodes have a %.0f%%-of-flux radius from %s'
          % (len(out), 100 * frac, os.path.basename(path)))
    _R_FLUX = out
    return _R_FLUX


def model_radius_as(fwhm, r_be, tag=None):
    """Radius, in arcsec, out to which a model must be kept clear of others.

    Two radii describe an injected model and they are not the same thing.

      TRUE footprint      R_BE, the truncation radius of the sphere.  All of
                          the model's signal lies inside it and none outside,
                          since the injected stamp has the crater background
                          removed.  This is the footprint in the physical
                          sense.
      OBSERVED footprint  0.5 * FOOTPRINT_FACTOR * FWHMSDbs, the radius getsf
                          would assign, set by the extraction rather than by
                          the source.  This is the area over which the flux is
                          actually measured.

    Either can be the larger.  Over the models the sampler places, the median
    ratio of R_BE to the observed footprint radius is 0.68, so the observed one
    usually dominates; but for the concentrated, large-xi_max models it does
    not, and one of them reaches R_BE = 199 arcsec on an observed width of only
    33 arcsec, a ratio of six.  Separating such a model on its observed
    footprint alone leaves its envelope free to swallow a compact neighbour.

    Neither, however, is the right radius for deciding whether two cores
    contaminate each other.  R_BE is where the signal formally stops, but for a
    concentrated model the outer envelope is far too faint to affect anything:
    node i03j18k08 has R_BE = 631 arcsec while 95% of its flux lies within 43.
    Enforcing R_BE clearance would exclude such models from a field containing
    real sources altogether, for the sake of a few per cent of their flux
    spread over a disk fifteen times wider.

    The radius used is therefore the one enclosing FLUX_FRACTION of the model's
    flux, measured from its own profile, and never less than the observed
    footprint, so that neither the bulk of the signal nor the area over which
    the flux is measured reaches into another core.  Without the profiles
    catalogue it falls back to the larger of R_BE and the observed footprint.
    """
    r_obs = 0.5 * FOOTPRINT_FACTOR * float(fwhm)
    if tag is not None:
        r_flux = _flux_radii().get(tag)
        if r_flux is not None and np.isfinite(r_flux) and r_flux > 0:
            return max(float(r_flux), r_obs)
    return max(float(r_be), r_obs)


def min_separation_as(rad_a, rad_b):
    """Smallest permitted centre separation of two injected cores, in arcsec.

    Arguments are the radii from model_radius_as.  With MAX_FOOTPRINT_OVERLAP
    set, the two may overlap by at most that fraction of the sum of their
    radii, and the rule applies to every pair.  Otherwise the older rule is
    used, in which the separation is SEP_FACTOR times the sum of the two radii.
    """
    if MAX_FOOTPRINT_OVERLAP is not None:
        return (1.0 - MAX_FOOTPRINT_OVERLAP) * (rad_a + rad_b)
    return SEP_FACTOR * (rad_a + rad_b)


